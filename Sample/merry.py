def animate_sunrise(sun):
     w = paper.getWidth()
     h = 350
     r = sun.getRadius()
     x0 = w / 2.0
     y0 = h + r
     max_x  = w / 2.0 - r
     max_y  = h
     for angle in range(721):
         rad = (angle/360.0) * math.pi
         x = x0 - max_x * math.cos(rad)
         y = y0 - max_y * math.sin(rad)
         
         sun.moveTo(x, y)
